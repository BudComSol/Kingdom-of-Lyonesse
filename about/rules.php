<div class="tophead">
    <b>Prohibited Actions:</b><br><br> 
    1. Insults, harassment, or verbal abuse towards players or game administration.<br><br> 
    2. Profanity, obscene language, vulgar abbreviations, and offensive remarks.<br><br> 
    3. Promotion of illegal substances, violence, explicit adult content, suicide, or cruelty.<br><br> 
    4. Deliberately instigating conflicts, slander, harassment campaigns, or unfounded accusations.<br><br> 
    5. Political debates, hate speech, racial or religious discrimination, and extremist propaganda.<br><br> 
    6. Commercial advertising, promoting external links/services, or spamming other games.<br><br> 
    7. Inappropriate character names (offensive words, hate symbols, impersonating admins or moderators).<br><br> 
    8. Spamming, excessive caps lock, chat flooding, trolling, or emoji spam (more than 5 in a row).<br><br> 
    9. Fraud, scams, phishing, or blackmail against other players or staff.<br><br> 
    10. Adult services, pornography, explicit imagery, and predatory behavior.<br><br> 
    11. Inciting other players to violate server rules.<br><br> 
    12. Public disputes with game staff or moderators in global chat.<br><br> 
    13. Destructive behaviors aimed at harming the game community or economy.<br><br> 
    14. Exploiting bugs, glitches, or vulnerabilities. Exploits must be reported immediately to staff.<br><br> 
    15. Third-party automation software, bots, macros, memory editors, or cheats.<br><br> 
    16. Real-money trading (RMT) of accounts, guild ownership, or items.<br><br> 
    17. Registering excessive alternate accounts to manipulate game systems (multi-accounting).<br><br> 
    18. Begging for gold, rubies, or equipment in public chat channels.
</div> 

